#!/usr/bin/env python3
"""Render app theme files from a palette: templates/**  ->  themes/<palette>/**.

Usage:
    tools/render_theme.py colors/quasar.toml           # write themes/quasar/
    tools/render_theme.py colors/quasar.toml --check   # exit 1 if committed output is stale

Template syntax: {{ role }} or {{ role | filter[:arg] }}. Roles are any palette role
(base ramp, accents) plus `bright_<accent>` for accent_bright and `name` for the palette name.
Filters:
    hex        #RRGGBB (default)
    hexa:A     #RRGGBBAA with alpha A in 0..1    (rasi, CSS)
    rgba:A     rgba(RRGGBBAA), A defaults to 1   (Hyprland, hyprlang)
    bare       RRGGBB                            (no prefix)
    vec3       vec3(r, g, b) in 0..1, sRGB       (GLSL shaders)
    qcolor:A   #AARRGGBB, A defaults to 1        (QML: Qt puts alpha FIRST, unlike CSS)
    rgbcsv     r,g,b decimal                     (KDE .colors schemes)
    cssrgba:A  rgba(r, g, b, a) decimal          (GTK3/GTK4 CSS; GTK3 has no #RRGGBBAA)
    sgr        r;g;b decimal                     (ANSI truecolor: 38;2;{{ x | sgr }})
A {{ }} that does not resolve is an error, so typos fail the build instead of shipping.
Dev-only: the installer copies/links the rendered files and never runs this.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from palette import load  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
TEMPLATES = ROOT / "templates"
TOKEN = re.compile(r"\{\{\s*(\w+)\s*(?:\|\s*(\w+)\s*(?::\s*([\d.]+))?)?\s*\}\}")
HEADER = {
    ".rasi": "/* Generated by tools/render_theme.py from {src}. Do not edit; edit the template. */\n",
    ".lua": "-- Generated by tools/render_theme.py from {src}. Do not edit; edit the template.\n",
    ".conf": "# Generated by tools/render_theme.py from {src}. Do not edit; edit the template.\n",
    ".css": "/* Generated by tools/render_theme.py from {src}. Do not edit; edit the template. */\n",
    ".frag": "// Generated by tools/render_theme.py from {src}. Do not edit; edit the template.\n",
    ".qml": "// Generated by tools/render_theme.py from {src}. Do not edit; edit the template.\n",
    ".toml": "# Generated by tools/render_theme.py from {src}. Do not edit; edit the template.\n",
    ".colors": "# Generated by tools/render_theme.py from {src}. Do not edit; edit the template.\n",
    ".js": "// Generated by tools/render_theme.py from {src}. Do not edit; edit the template.\n",
    ".json": "",
    ".zsh": "# Generated by tools/render_theme.py from {src}. Do not edit; edit the template.\n",
    ".ini": "# Generated by tools/render_theme.py from {src}. Do not edit; edit the template.\n",
    ".sh": "# Generated by tools/render_theme.py from {src}. Do not edit; edit the template.\n",
    ".theme": "# Generated by tools/render_theme.py from {src}. Do not edit; edit the template.\n",
    ".xcu": "",   # XML: nothing may precede the <?xml ?> declaration; the files carry a comment inside
    ".xml": "",
    ".jsonc": "// Generated by tools/render_theme.py from {src}. Do not edit; edit the template.\n",
}

# Files whose format needs a different comment marker than their extension suggests.
HEADER_BY_NAME = {
    "texstudio.ini": "; Generated by tools/render_theme.py from {src}. Do not edit; edit the template.\n",  # QSettings: ';'
    "config": "# Generated by tools/render_theme.py from {src}. Do not edit; edit the template.\n",  # imv (no extension)
    "dunstrc": "# Generated by tools/render_theme.py from {src}. Do not edit; edit the template.\n",
    "zathurarc": "# Generated by tools/render_theme.py from {src}. Do not edit; edit the template.\n",
}


def roles(pal: dict) -> dict[str, str]:
    out = dict(pal["base"]) | dict(pal["accent"])
    out |= {f"bright_{k}": v for k, v in pal["accent_bright"].items()}
    return out


def alpha_byte(a: str | None, default: float = 1.0) -> str:
    v = default if a is None else float(a)
    if not 0 <= v <= 1:
        raise ValueError(f"alpha {v} outside 0..1")
    return f"{round(v * 255):02X}"


def render(text: str, table: dict[str, str], name: str, where: str) -> str:
    def sub(m: re.Match) -> str:
        role, flt, arg = m.group(1), m.group(2) or "hex", m.group(3)
        if role == "name":
            return name
        if role not in table:
            raise SystemExit(f"{where}: unknown role '{role}'")
        hexv = table[role].lstrip("#").upper()
        if flt == "hex":
            return f"#{hexv}"
        if flt == "hexa":
            return f"#{hexv}{alpha_byte(arg)}"
        if flt == "rgba":
            return f"rgba({hexv}{alpha_byte(arg)})"
        if flt == "bare":
            return hexv
        if flt == "qcolor":
            return f"#{alpha_byte(arg)}{hexv}"
        if flt == "rgbcsv":                     # KDE color schemes: r,g,b
            return ",".join(str(int(hexv[i:i + 2], 16)) for i in (0, 2, 4))
        if flt == "sgr":                        # truecolor SGR parameters: r;g;b (use as 38;2;… / 48;2;…)
            return ";".join(str(int(hexv[i:i + 2], 16)) for i in (0, 2, 4))
        if flt == "cssrgba":                    # GTK3/GTK4 CSS: rgba(r, g, b, a)
            r, g, b = (int(hexv[i:i + 2], 16) for i in (0, 2, 4))
            a = 1.0 if arg is None else float(arg)
            return f"rgba({r}, {g}, {b}, {a:g})"
        if flt == "int":                        # LibreOffice registry colors: 0xRRGGBB as a decimal int
            return str(int(hexv[0:6], 16))
        if flt == "vec3":
            r, g, b = (int(hexv[i:i + 2], 16) / 255 for i in (0, 2, 4))
            return f"vec3({r:.4f}, {g:.4f}, {b:.4f})"
        raise SystemExit(f"{where}: unknown filter '{flt}'")
    return TOKEN.sub(sub, text)


def build(palette_path: Path) -> dict[Path, str]:
    pal = load(palette_path)
    table, name = roles(pal), pal["meta"]["name"]
    out_root = ROOT / "themes" / palette_path.stem
    rel_src = palette_path.resolve().relative_to(ROOT)
    files = {}
    for tpl in sorted(TEMPLATES.rglob("*")):
        if not tpl.is_file():
            continue
        rel = tpl.relative_to(TEMPLATES)
        body = render(tpl.read_text(), table, name, str(rel))
        header = HEADER_BY_NAME.get(tpl.name, HEADER.get(tpl.suffix, "")).format(src=rel_src)
        files[out_root / rel] = header + body
    return files


def main(argv: list[str]) -> int:
    args = [a for a in argv[1:] if not a.startswith("--")]
    if len(args) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    files = build(Path(args[0]))
    if "--check" in argv:
        stale = [p for p, body in files.items() if not p.exists() or p.read_text() != body]
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}")
        return 1 if stale else 0
    for p, body in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(body)
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
