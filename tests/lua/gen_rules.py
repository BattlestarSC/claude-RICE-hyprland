#!/usr/bin/env python3
"""Regenerate tests/lua/rules.lua (window/layer rule keys, event names) from the Hyprland wiki.

    git clone --depth 1 https://github.com/hyprwm/hyprland-wiki /tmp/wiki
    python3 tests/lua/gen_rules.py /tmp/wiki > tests/lua/rules.lua

Reads content/configuring/core/rules/{window,layer}-rules.md (first column of the "Prop" and
"Effect" tables) and advanced-configuration/events.md (first column of the "Event" table).
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path


def first_column(path: Path, header: str) -> set[str]:
    """Names in every table whose header row starts with `| <header> |`."""
    names: set[str] = set()
    inside = False
    for line in path.read_text().splitlines():
        if re.match(rf"\|\s*{header}\s*\|", line):
            inside = True
            continue
        if inside and not line.startswith("|"):
            inside = False
        if inside and (m := re.match(r"\|\s*`?([a-z_][a-z_0-9.]*)`?\s*\|", line)):
            names.add(m.group(1))
    return names


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    wiki = Path(argv[1])
    core = wiki / "content/configuring/core"
    rev = subprocess.run(["git", "-C", str(wiki), "log", "-1", "--format=%h %cs"],
                         capture_output=True, text=True).stdout.strip() or "unknown"
    tables = {
        "window_props": first_column(core / "rules/window-rules.md", "Prop"),
        "window_effects": first_column(core / "rules/window-rules.md", "Effect"),
        "layer_props": first_column(core / "rules/layer-rules.md", "Prop"),
        "layer_effects": first_column(core / "rules/layer-rules.md", "Effect"),
        "events": first_column(core / "advanced-configuration/events.md", "Event"),
    }
    print(f"-- Generated by tests/lua/gen_rules.py from hyprland-wiki {rev}. Do not edit.")
    print("return {")
    for name, items in tables.items():
        print(f"    {name} = {{")
        for item in sorted(items):
            print(f'        ["{item}"] = true,')
        print("    },")
    print("}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
