#!/usr/bin/env python3
"""Regenerate tests/lua/options.lua (valid hl.config option paths) from the Hyprland wiki.

    git clone --depth 1 https://github.com/hyprwm/hyprland-wiki /tmp/wiki
    python3 tests/lua/gen_options.py /tmp/wiki > tests/lua/options.lua

Reads content/configuring/core/config-options.md: every "Category: `x`" line opens a scope and
every table row below it names one option x.<name>.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    wiki = Path(argv[1])
    src = wiki / "content/configuring/core/config-options.md"
    rev = subprocess.run(["git", "-C", str(wiki), "log", "-1", "--format=%h %cs"],
                         capture_output=True, text=True).stdout.strip() or "unknown"
    cat, opts = None, set()
    for line in src.read_text().splitlines():
        m = re.match(r"Category: `([\w.]+)`", line.strip())
        if m:
            cat = m.group(1)
            continue
        m = re.match(r"\|\s*`?([a-z_0-9:.]+)`?\s*\|", line)
        if m and cat and m.group(1) != "name":
            opts.add(f"{cat}.{m.group(1)}")
    print(f"-- Generated by tests/lua/gen_options.py from hyprland-wiki {rev} "
          "(content/configuring/core/config-options.md). Do not edit.")
    print("return {")
    for o in sorted(opts):
        print(f'    ["{o}"] = true,')
    print("}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
